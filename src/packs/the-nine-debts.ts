/**
 * The Nine Debts — a city that has been drinking on credit for four hundred years.
 *
 * The design problem this pack is written against is the Referee's. A magic
 * system authored as a list of capabilities gives the adjudicator nothing to
 * refuse with, so it says yes to everything a player asks for. This world
 * therefore has no spell list at all. It has a *lien*: to make the world do
 * something it would not otherwise do, a second person must be present and must
 * say aloud, in words specific enough to lose, what it will take from them —
 * and it takes exactly that. The concepts in this pack are consequently written
 * as refusals (`concept:what-the-lien-refuses`, `concept:the-turning`) rather
 * than as powers, and every cost has a creditor with a name, a face and a
 * grievance, because an abstraction cannot come to collect.
 *
 * The same mechanism runs at civic scale. Four hundred years ago the Rethen cut
 * a channel through the salt hill and put the river back on the plain, and nine
 * human houses signed for it in nine instalments. Eight have been paid. The
 * ninth falls due at the turn of this dry season, and the house that owes it has
 * failed — which under Rethen law changes nothing, because a debt cannot be
 * forgiven, only paid, transferred, or inherited. Somebody in Ossenhalt
 * inherited it. Several parties have worked out who, separately, and each has a
 * reason not to say.
 *
 * Nobody is rising. Nothing is awakening. If every person in this pack does
 * exactly what their interests recommend, the lien turns on the appointed day
 * and the water goes back under the hill, and that is the whole engine.
 */
